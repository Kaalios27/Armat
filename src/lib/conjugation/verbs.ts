const LOOKUP = new Map<string, VerbDef>(VERBS.filter((d) => !d.inf.includes(" ")).map((d) => [d.inf, d]));

export function getVerbDef(inf: string): VerbDef | undefined {
  return LOOKUP.get(inf);
}

export function conjugableVerbs(): VerbDef[] {
  return VERBS.filter((d) => !d.inf.includes(" "));
}
