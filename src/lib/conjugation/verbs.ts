type Opts = Omit<VerbDef, "inf" | "en" | "fr" | "level">;

function v(inf: string, en: string, fr: string, level: 1 | 2 | 3, opts: Opts = {}): VerbDef {
  const core = inf.replace(/se$/, "");
  const irr = opts.irr ?? (IRR[core] && !opts.compound ? IRR[core] : undefined);
  return { inf, en, fr, level, ...opts, ...(irr ? { irr } : {}) };
}

