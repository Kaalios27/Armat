import { readFileSync } from "node:fs";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { closeDatabase, type DB } from "@/core/db/client";
import { conceptProgress, profile, studySessions, vocabCards } from "@/core/db/schema";
import { setClock } from "@/core/engine/clock";
import { exportAll, importAll, ImportError, resetProgress } from "@/core/services/export";
import { answerItem, ensureTodaySession, nextItem } from "@/core/services/session";
import { useTestDb } from "./support/db";
// @ts-expect-error: plain ESM script without type declarations
import { renderMigrations } from "../scripts/gen-migrations.mjs";

let db: DB;
const TZ = "Europe/Madrid";

beforeAll(async () => {
  setClock(() => new Date("2026-11-23T08:00:00Z"));
  db = await useTestDb();
  // Some history: start today's session and answer the first vocabulary items.
  const t = await ensureTodaySession(TZ);
  for (let i = 0; i < 4; i++) {
    const r = await nextItem(t.session!.id, "vocab", i * 1000, TZ);
    if (r.type !== "item") break;
    await answerItem(t.session!.id, r.item.id, r.item.kind === "vocab-intro" ? { action: "seen" } : { rating: 3 }, undefined, TZ);
  }
});

afterAll(async () => {
  setClock(null);
  await closeDatabase();
});

describe("bundled migrations", () => {
  it("match the SQL files generated by drizzle-kit", () => {
    expect(readFileSync("src/core/db/migrations.ts", "utf8").replace(/\r\n/g, "\n")).toBe(renderMigrations("."));
  });
});

describe("export and import", () => {
  it("round-trips all learner data through JSON", async () => {
    const data = JSON.parse(JSON.stringify(await exportAll()));
    expect(data.format).toBe("armat-export");
    expect(data.vocabCards.length).toBeGreaterThan(0);
    const before = { sessions: (await db.select().from(studySessions)).length, cards: (await db.select().from(vocabCards)).length };

    await resetProgress();
    expect(await db.select().from(studySessions)).toHaveLength(0);
    expect(await db.select().from(vocabCards)).toHaveLength(0);
    expect((await db.select().from(profile))[0]!.startedOn).toBeNull();

    const counts = await importAll(data);
    expect(counts.vocabCards).toBe(before.cards);
    expect(await db.select().from(studySessions)).toHaveLength(before.sessions);
    const card = (await db.select().from(vocabCards))[0]!;
    // Timestamps come back as dates, not strings.
    expect(card.dueAt).toBeInstanceOf(Date);
    expect((await db.select().from(profile))[0]!.startedOn).toBe("2026-11-23");
  });

  it("rejects files that are not exports and skips rows for unknown content", async () => {
    await expect(importAll({ hello: "world" })).rejects.toBeInstanceOf(ImportError);
    await expect(importAll({ format: "armat-export", version: 99 })).rejects.toBeInstanceOf(ImportError);
    const data = JSON.parse(JSON.stringify(await exportAll()));
    data.vocabCards.push({ ...data.vocabCards[0], id: "x-unknown", itemId: "v-does-not-exist" });
    data.conceptProgress.push({ conceptId: "g-does-not-exist", mastery: 0.5 });
    const counts = await importAll(data);
    expect(counts.vocabCards).toBe(data.vocabCards.length - 1);
    expect((await db.select().from(conceptProgress)).some((r) => r.conceptId === "g-does-not-exist")).toBe(false);
  });
});
